import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";
import fs from "fs";
import path from "path";

const mode = process.argv[2] || "dev"; // dev | production | harness | web
const production = mode === "production";

// Where to copy the built plugin for live testing in the real vault, so a
// rebuild only needs an Obsidian reload. Override with
// HEBREW_DA_TEST_VAULT_PLUGIN_DIR if this path isn't yours.
// Skipped on build servers (CI), where that path doesn't exist.
const testVaultPluginDir = process.env.CI ? "" :
	process.env.HEBREW_DA_TEST_VAULT_PLUGIN_DIR ||
	"C:\\Users\\11tdr\\Documents\\Obsidian\\CryptaMei\\.obsidian\\plugins\\hebrew-da";

const copyToVaultPlugin = {
	name: "copy-to-test-vault",
	setup(build) {
		build.onEnd(result => {
			if (result.errors.length || !testVaultPluginDir) return;
			try {
				fs.mkdirSync(testVaultPluginDir, { recursive: true });
				for (const file of ["main.js", "manifest.json", "styles.css"]) {
					fs.copyFileSync(path.resolve(file), path.join(testVaultPluginDir, file));
				}
				console.log(`Copied build to ${testVaultPluginDir}`);
			} catch (err) {
				console.error(`Failed to copy build to test vault (${testVaultPluginDir}):`, err.message);
			}
		});
	},
};

// The harness bundles the same view into a plain web page (dev/index.html)
// with a small stand-in for the Obsidian API, so the UI can be checked in a
// browser without reloading Obsidian.
const harness = mode === "harness";

// The web version (GitHub Pages) is built into docs/: the view plus
// web/app.ts, with web/obsidian-web.ts standing in for the Obsidian API.
const web = mode === "web";
const webOut = "docs";
const copyWebFiles = {
	name: "copy-web-files",
	setup(build) {
		build.onEnd(result => {
			if (result.errors.length) return;
			fs.copyFileSync("styles.css", path.join(webOut, "styles.css"));
			fs.copyFileSync("web/index.html", path.join(webOut, "index.html"));
			fs.copyFileSync("web/web.css", path.join(webOut, "web.css"));
			fs.writeFileSync(path.join(webOut, ".nojekyll"), "");
			console.log(`Web version written to ${webOut}/`);
		});
	},
};

const browser = harness || web;
const context = await esbuild.context({
	banner: {
		js: "/* THIS IS A GENERATED/BUNDLED FILE BY ESBUILD. If you want to view the source, visit the src/ directory. */",
	},
	entryPoints: [web ? "web/app.ts" : harness ? "dev/harness.ts" : "src/main.ts"],
	bundle: true,
	external: browser ? [] : [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtins,
	],
	alias: web ? { obsidian: "./web/obsidian-web.ts" } : harness ? { obsidian: "./dev/obsidian-shim.ts" } : undefined,
	format: browser ? "iife" : "cjs",
	target: "es2020",
	logLevel: "info",
	sourcemap: production || web ? false : "inline",
	treeShaking: true,
	outfile: web ? `${webOut}/app.js` : harness ? "dev/harness.js" : "main.js",
	minify: production || web,
	plugins: web ? [copyWebFiles] : browser ? [] : [copyToVaultPlugin],
});

if (production || browser) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
